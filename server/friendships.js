function friendshipSchema(dialect = 'postgres') {
  const id = dialect === 'sqlite' ? 'INTEGER PRIMARY KEY' : 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
  const timestamp = dialect === 'sqlite' ? 'TEXT' : 'TIMESTAMPTZ';
  return `
    CREATE TABLE IF NOT EXISTS amizades (
      id ${id},
      usuario_a_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
      usuario_b_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
      remetente_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
      estado TEXT NOT NULL DEFAULT 'pendente' CHECK (estado IN ('pendente', 'aceita')),
      criado_em ${timestamp} NOT NULL DEFAULT CURRENT_TIMESTAMP,
      aceito_em ${timestamp},
      CHECK (usuario_a_id < usuario_b_id),
      CHECK (remetente_id = usuario_a_id OR remetente_id = usuario_b_id),
      UNIQUE (usuario_a_id, usuario_b_id)
    );
    CREATE INDEX IF NOT EXISTS amizades_usuario_a_estado_idx ON amizades(usuario_a_id, estado);
    CREATE INDEX IF NOT EXISTS amizades_usuario_b_estado_idx ON amizades(usuario_b_id, estado);
  `;
}

class FriendshipError extends Error {
  constructor(status, message, code) {
    super(message);
    this.status = status;
    this.code = code;
  }
}

function validUserId(value) {
  const id = Number(value);
  return Number.isSafeInteger(id) && id > 0 ? id : null;
}

function requireId(value) {
  const id = validUserId(value);
  if (!id) throw new FriendshipError(400, 'Identificador inválido.', 'ID_INVALIDO');
  return id;
}

function pairFor(a, b) {
  return [Math.min(a, b), Math.max(a, b)];
}

const publicUserFields = 'u.id, u.nome, u.avatar_cor, u.avatar_url, u.status';

function createFriendshipService({ all, get, run }) {
  async function areFriends(userId, otherId) {
    const a = validUserId(userId);
    const b = validUserId(otherId);
    if (!a || !b || a === b) return false;
    return Boolean(await get(
      "SELECT id FROM amizades WHERE usuario_a_id = ? AND usuario_b_id = ? AND estado = 'aceita'",
      ...pairFor(a, b),
    ));
  }

  async function listFriends(userId) {
    return all(
      `SELECT ${publicUserFields}
       FROM amizades a JOIN usuarios u
         ON u.id = CASE WHEN a.usuario_a_id = ? THEN a.usuario_b_id ELSE a.usuario_a_id END
       WHERE (a.usuario_a_id = ? OR a.usuario_b_id = ?) AND a.estado = 'aceita'
       ORDER BY LOWER(u.nome), u.id`,
      userId, userId, userId,
    );
  }

  async function listRequests(userId) {
    const rows = await all(
      `SELECT a.id AS pedido_id, a.remetente_id, a.criado_em, ${publicUserFields}
       FROM amizades a JOIN usuarios u
         ON u.id = CASE WHEN a.usuario_a_id = ? THEN a.usuario_b_id ELSE a.usuario_a_id END
       WHERE (a.usuario_a_id = ? OR a.usuario_b_id = ?) AND a.estado = 'pendente'
       ORDER BY a.id DESC`,
      userId, userId, userId,
    );
    const result = { recebidos: [], enviados: [] };
    for (const { pedido_id, remetente_id, criado_em, ...usuario } of rows) {
      const direction = Number(remetente_id) === Number(userId) ? 'enviados' : 'recebidos';
      result[direction].push({ id: pedido_id, criado_em, usuario });
    }
    return result;
  }

  async function findUser(name) {
    if (typeof name !== 'string' || !name.trim() || name.trim().length > 128) {
      throw new FriendshipError(400, 'Informe o nome ou identificador do seu amigo.', 'NOME_INVALIDO');
    }
    const text = name.trim();
    const identifier = text.match(/^(.*?)#([1-9]\d*)$/);
    if (identifier) {
      const id = validUserId(identifier[2]);
      const user = id ? await get(`SELECT ${publicUserFields} FROM usuarios u WHERE u.id = ?`, id) : null;
      if (!user || (identifier[1] && user.nome.trim().toLowerCase() !== identifier[1].trim().toLowerCase())) {
        throw new FriendshipError(404, 'Pessoa não encontrada. Confira o identificador.', 'USUARIO_NAO_ENCONTRADO');
      }
      return user;
    }
    const users = await all(
      `SELECT ${publicUserFields} FROM usuarios u WHERE LOWER(TRIM(u.nome)) = LOWER(?) ORDER BY u.id LIMIT 2`,
      text,
    );
    if (users.length > 1) {
      throw new FriendshipError(409, 'Há mais de uma pessoa com esse nome. Peça o identificador no formato Nome#ID.', 'NOME_AMBIGUO');
    }
    if (!users.length) throw new FriendshipError(404, 'Pessoa não encontrada. Confira o nome ou use Nome#ID.', 'USUARIO_NAO_ENCONTRADO');
    return users[0];
  }

  async function sendRequest(userId, name) {
    const requesterId = requireId(userId);
    const user = await findUser(name);
    if (Number(user.id) === requesterId) {
      throw new FriendshipError(400, 'Você não pode adicionar a si mesmo.', 'AUTO_AMIZADE');
    }
    const pair = pairFor(requesterId, Number(user.id));
    // The unique pair makes simultaneous and reverse invitations one request.
    const inserted = await get(
      `INSERT INTO amizades (usuario_a_id, usuario_b_id, remetente_id)
       VALUES (?, ?, ?) ON CONFLICT (usuario_a_id, usuario_b_id) DO NOTHING RETURNING id, criado_em`,
      ...pair, requesterId,
    );
    if (!inserted) {
      const existing = await get(
        'SELECT estado, remetente_id FROM amizades WHERE usuario_a_id = ? AND usuario_b_id = ?',
        ...pair,
      );
      if (existing?.estado === 'aceita') {
        throw new FriendshipError(409, 'Essa pessoa já está na sua lista de amigos.', 'AMIZADE_EXISTENTE');
      }
      if (Number(existing?.remetente_id) === requesterId) {
        throw new FriendshipError(409, 'Você já enviou um pedido para essa pessoa.', 'PEDIDO_ENVIADO');
      }
      throw new FriendshipError(409, 'Essa pessoa já enviou um pedido para você. Aceite-o na aba Pendentes.', 'PEDIDO_RECEBIDO');
    }
    return { pedido: { ...inserted, usuario: user }, usuarioIds: pair };
  }

  async function acceptRequest(userId, requestId) {
    const id = requireId(requestId);
    const result = await get(
      `UPDATE amizades SET estado = 'aceita', aceito_em = CURRENT_TIMESTAMP
       WHERE id = ? AND estado = 'pendente' AND remetente_id != ?
         AND (usuario_a_id = ? OR usuario_b_id = ?)
       RETURNING usuario_a_id, usuario_b_id`,
      id, userId, userId, userId,
    );
    if (!result) throw new FriendshipError(404, 'Pedido de amizade não encontrado.', 'PEDIDO_NAO_ENCONTRADO');
    return { usuarioIds: [result.usuario_a_id, result.usuario_b_id] };
  }

  async function deleteRequest(userId, requestId) {
    const id = requireId(requestId);
    const result = await get(
      `DELETE FROM amizades WHERE id = ? AND estado = 'pendente'
         AND (usuario_a_id = ? OR usuario_b_id = ?)
       RETURNING usuario_a_id, usuario_b_id`,
      id, userId, userId,
    );
    if (!result) throw new FriendshipError(404, 'Pedido de amizade não encontrado.', 'PEDIDO_NAO_ENCONTRADO');
    return { usuarioIds: [result.usuario_a_id, result.usuario_b_id] };
  }

  async function removeFriend(userId, otherId) {
    const pair = pairFor(requireId(userId), requireId(otherId));
    const result = await run(
      "DELETE FROM amizades WHERE usuario_a_id = ? AND usuario_b_id = ? AND estado = 'aceita'",
      ...pair,
    );
    if (!result.changes) throw new FriendshipError(404, 'Amizade não encontrada.', 'AMIZADE_NAO_ENCONTRADA');
    return { usuarioIds: pair };
  }

  async function shareServer(userId, otherId) {
    return Boolean(await get(
      `SELECT 1 FROM membros_servidor m1 JOIN membros_servidor m2 ON m2.servidor_id = m1.servidor_id
       WHERE m1.usuario_id = ? AND m2.usuario_id = ?`,
      userId, otherId,
    ));
  }

  async function canMessage(userId, otherId) {
    const a = validUserId(userId);
    const b = validUserId(otherId);
    if (!a || !b || a === b) return false;
    return await areFriends(a, b) || await shareServer(a, b);
  }

  async function listMessages(userId, otherId) {
    return all(
      `SELECT m.id, m.conteudo, m.criado_em, m.remetente_id FROM mensagens_diretas m
       WHERE (m.remetente_id = ? AND m.destinatario_id = ?) OR (m.remetente_id = ? AND m.destinatario_id = ?)
       ORDER BY m.id LIMIT 100`,
      userId, otherId, otherId, userId,
    );
  }

  return { areFriends, listFriends, listRequests, sendRequest, acceptRequest, deleteRequest, removeFriend, shareServer, canMessage, listMessages };
}

module.exports = { friendshipSchema, createFriendshipService, FriendshipError };
